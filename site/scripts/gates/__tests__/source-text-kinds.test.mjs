/**
 * Unit tests for the backlog-#38 split: `data-source-text` grants a CITATION
 * exemption to every marked subtree, but the two FORMATTING exemptions are
 * granted per marker VALUE by source-text-kinds.mjs, and the site's own
 * explanatory prose gets neither.
 *
 * Run via `npm test` (vitest).
 */

import { describe, it, expect } from "vitest";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

import {
  SOURCE_TEXT_KINDS,
  KNOWN_SOURCE_TEXT_KINDS,
  isKnownSourceTextKind,
  exemptFromCurrencyScan,
  exemptFromNotationSweep,
} from "../source-text-kinds.mjs";
import {
  pagePathFromRelPath,
  makeProseAllowlist,
} from "../prose-allowlist.mjs";

const gatesDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.resolve(gatesDir, "..", "..", "src");

// ── the registry itself ──────────────────────────────────────────────────────

describe("SOURCE_TEXT_KINDS registry", () => {
  it("every kind declares both exemptions and a written reason", () => {
    for (const [name, kind] of Object.entries(SOURCE_TEXT_KINDS)) {
      expect(typeof kind.quotedFigures, name).toBe("boolean");
      expect(typeof kind.sourceNotation, name).toBe("boolean");
      expect(kind.why.length, name).toBeGreaterThan(40);
    }
  });

  it("classifies quoted source prose as exempt from both sweeps", () => {
    for (const v of ["narrative", "dossier-claim", "lineage-evidence"]) {
      expect(exemptFromCurrencyScan(v), v).toBe(true);
      expect(exemptFromNotationSweep(v), v).toBe(true);
    }
  });

  it("exporter-composed headlines keep the currency exemption but NOT the notation one", () => {
    // The sentence is generated by our own export pipeline, so its integer
    // notation is ours to get right even though its dollar tokens cannot
    // carry per-token anchors today.
    expect(exemptFromCurrencyScan("headline")).toBe(true);
    expect(exemptFromNotationSweep("headline")).toBe(false);
  });

  it('"methodology" is no longer a source-text kind at all', () => {
    // The site's own explanatory prose quotes nothing; it must be visible to
    // both sweeps. This is the backlog-#38 defect, asserted as absent.
    expect(isKnownSourceTextKind("methodology")).toBe(false);
    expect(exemptFromCurrencyScan("methodology")).toBe(false);
    expect(exemptFromNotationSweep("methodology")).toBe(false);
  });

  it("an unclassified marker value buys no exemption", () => {
    expect(isKnownSourceTextKind("whatever-i-just-invented")).toBe(false);
    expect(exemptFromCurrencyScan("whatever-i-just-invented")).toBe(false);
    expect(exemptFromNotationSweep("whatever-i-just-invented")).toBe(false);
    expect(exemptFromCurrencyScan(null)).toBe(false);
    expect(exemptFromNotationSweep(undefined)).toBe(false);
  });
});

// ── the marker values the SOURCE actually renders ────────────────────────────

describe("data-source-text values in src/", () => {
  /**
   * Every literal `data-source-text="…"` the TSX sources actually RENDER.
   * Comments are stripped first — the marker names appear in prose there
   * (including in the note explaining why /methodology/ no longer carries one).
   */
  function markerValuesInSource(dir) {
    const found = new Set();
    const stripComments = (s) =>
      s
        .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, "") // {/* JSX comment */}
        .replace(/\/\*[\s\S]*?\*\//g, "") //          /* block comment */
        .replace(/^[ \t]*\/\/.*$/gm, ""); //          // line comment
    const walk = (d) => {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const p = path.join(d, e.name);
        if (e.isDirectory()) {
          if (e.name !== "__tests__") walk(p);
          continue;
        }
        if (!/\.tsx?$/.test(e.name) || /\.test\.tsx?$/.test(e.name)) continue;
        const text = stripComments(fs.readFileSync(p, "utf8"));
        for (const m of text.matchAll(/data-source-text=["']([a-z-]+)["']/g)) {
          found.add(m[1]);
        }
      }
    };
    walk(dir);
    return found;
  }

  it("every value the site renders is classified in the registry", () => {
    const rendered = [...markerValuesInSource(srcDir)].sort();
    expect(rendered.length).toBeGreaterThan(0);
    const unknown = rendered.filter((v) => !isKnownSourceTextKind(v));
    expect(unknown, `unclassified data-source-text value(s): ${unknown}`).toEqual([]);
  });

  it("no page marks its own explanatory prose as source text", () => {
    const rendered = markerValuesInSource(srcDir);
    expect(rendered.has("methodology")).toBe(false);
  });

  it("the registry has no entry the site never renders", () => {
    const rendered = markerValuesInSource(srcDir);
    // footnote-preview is client-only (never in the static HTML) but IS
    // rendered by panel.tsx, so it appears in source.
    const dead = KNOWN_SOURCE_TEXT_KINDS.filter((k) => !rendered.has(k));
    expect(dead, `registry kind(s) nothing renders: ${dead}`).toEqual([]);
  });
});

// ── page-path derivation ─────────────────────────────────────────────────────

describe("pagePathFromRelPath", () => {
  it("maps built index files to reader-facing page paths", () => {
    expect(pagePathFromRelPath("index.html")).toBe("/");
    expect(pagePathFromRelPath("methodology/index.html")).toBe("/methodology/");
    expect(pagePathFromRelPath("program/0400D/index.html")).toBe("/program/0400D/");
  });

  it("leaves non-index files addressable", () => {
    expect(pagePathFromRelPath("404.html")).toBe("/404.html");
  });
});

// ── the prose allowlist ──────────────────────────────────────────────────────

describe("makeProseAllowlist", () => {
  const entry = (pattern, pages, reason = "because") => ({ pattern, pages, reason });

  it("honours page scope — the field the gate used to ignore", () => {
    const al = makeProseAllowlist([entry("$50M", ["/methodology/", "/feed/"])]);
    expect(al.shapeErrors).toEqual([]);
    expect(al.isAllowed("/methodology/", "$50M")).toBe(true);
    expect(al.isAllowed("/feed/", "$50M")).toBe(true);
    expect(al.isAllowed("/program/0400D/", "$50M")).toBe(false);
  });

  it('supports the "*" wildcard for genuinely site-wide literals', () => {
    const al = makeProseAllowlist([entry("$0", ["*"])]);
    expect(al.isAllowed("/anything/", "$0")).toBe(true);
  });

  it("matches the exact token only", () => {
    const al = makeProseAllowlist([entry("$50M", ["/methodology/"])]);
    expect(al.isAllowed("/methodology/", "$5M")).toBe(false);
    expect(al.isAllowed("/methodology/", "$50.5M")).toBe(false);
    expect(al.isAllowed("/methodology/", " $50M ")).toBe(true); // whitespace only
  });

  it("rejects a pattern the currency scan could never produce", () => {
    const al = makeProseAllowlist([entry("currency examples", ["/methodology/"])]);
    expect(al.shapeErrors.join(" ")).toMatch(/not a currency token/);
    expect(al.isAllowed("/methodology/", "currency examples")).toBe(false);
  });

  it("requires a page scope and a written reason", () => {
    expect(makeProseAllowlist([{ pattern: "$1M", reason: "x" }]).shapeErrors.join(" ")).toMatch(
      /"pages" must be a non-empty array/,
    );
    expect(
      makeProseAllowlist([{ pattern: "$1M", pages: ["/x/"] }]).shapeErrors.join(" "),
    ).toMatch(/"reason" is required/);
  });

  it("reports an entry that matched nothing as a stale exemption", () => {
    const al = makeProseAllowlist([
      entry("$50M", ["/methodology/"]),
      entry("$999B", ["/methodology/"]),
    ]);
    al.isAllowed("/methodology/", "$50M");
    const unused = al.unusedErrors();
    expect(unused).toHaveLength(1);
    expect(unused[0]).toMatch(/\$999B/);
    expect(unused[0]).toMatch(/stale exemption/);
  });
});

// ── the shipped allowlist file ───────────────────────────────────────────────

describe("prose-allowlist.json as shipped", () => {
  const entries = JSON.parse(
    fs.readFileSync(path.join(gatesDir, "prose-allowlist.json"), "utf8"),
  );

  it("is structurally clean", () => {
    expect(makeProseAllowlist(entries).shapeErrors).toEqual([]);
  });

  it("scopes every entry to named pages rather than the whole site", () => {
    // A site-wide "*" is legal but must be a deliberate choice; today none of
    // the entries needs one, and a page-scoped exemption is the narrower rule.
    for (const e of entries) {
      expect(e.pages, e.pattern).not.toContain("*");
    }
  });

  it("covers the /methodology/ threshold and worked-example tokens", () => {
    const al = makeProseAllowlist(entries);
    for (const token of ["$50M", "$5M", "$1M", "$7.07B", "$4.92B", "$4.15B"]) {
      expect(al.isAllowed("/methodology/", token), token).toBe(true);
    }
    // …and does not leak them onto program pages.
    expect(al.isAllowed("/program/0400D/", "$7.07B")).toBe(false);
  });
});
